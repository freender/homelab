# --- refusals and secrets -----------------------------------------------------


@pytest.mark.parametrize(
    ("kwargs", "message"),
    [
        ({"tokens": "# empty\n"}, "PBS_BACKUP_MAIN_PASSWORD"),
        ({"key": False}, "keyfile was not staged"),
        ({"jobs": job_plan(vmid="105", exclude="105")}, "both vmid and exclude"),
        (
            {"storage": STORAGE_PLAN.replace("STORAGE_0_USERNAME='pve-backup@pbs'\n", "")},
            "missing STORAGE_0_USERNAME",
        ),
        (
            {"storage": STORAGE_PLAN.replace("ENCRYPTION='true'", "ENCRYPTION='yes'")},
            "true or false",
        ),
        ({"restore": restore_plan().replace("VMID='105'", "VMID='10 5'")}, "invalid LXC VMID"),
    ],
)
def test_every_refusal_comes_before_any_write_and_destroys_secrets(
    node: Node, kwargs: dict, message: str
) -> None:
    node.storages.clear()
    node.jobs.clear()
    node.stage(**kwargs)
    (node.build / "pbs-0.env").write_text("PBS_PASSWORD=x\n")

    with pytest.raises(InstallError, match=message):
        node.deploy()

    assert node.writes == []
    assert not Path(node.m.PERSISTENT_KEYFILE).exists()
    assert sorted(path.name for path in node.build.iterdir() if "pbs" in path.name) == []


def test_staged_secrets_are_destroyed_after_a_successful_deploy(node: Node) -> None:
    node.stage()
    (node.build / "pbs-1.env").write_text("PBS_PASSWORD=x\n")

    node.deploy()

    assert {path.name for path in node.build.iterdir()} == {"storage-plan.conf", "jobs-plan.conf"}


def test_a_node_with_no_plans_does_nothing(node: Node) -> None:
    node.deploy()

    assert node.writes == []


