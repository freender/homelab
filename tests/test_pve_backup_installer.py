def load_installer():
    spec = importlib.util.spec_from_file_location("pve_backup_installer", INSTALLER_PATH)
    assert spec and spec.loader
    module = importlib.util.module_from_spec(spec)
    # Registered before exec: `@dataclass` resolves annotations through sys.modules.
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


def options(argv: list[str]) -> dict[str, object]:
    values: dict[str, object] = {}
    for flag, value in zip(argv[::2], argv[1::2], strict=True):
        key = flag.removeprefix("--")
        if key == "exclude-path":
            values.setdefault(key, []).append(value)  # type: ignore[union-attr]
        else:
            values[key] = value
    return values


class Node:
    """One PVE node: storage.cfg entries, `.pw` files, vzdump jobs, containers, and
    the PBS datastores the restore step reads from."""

    def __init__(self, tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
        self.m = load_installer()
        self.tmp = tmp_path
        self.pve = tmp_path / "etc" / "pve"
        (self.pve / "priv" / "storage").mkdir(parents=True)
        for name, value in {
            "PERSISTENT_KEYFILE": str(tmp_path / "etc" / "homelab" / "pbs-encryption.key"),
            "STORAGE_CFG": str(self.pve / "storage.cfg"),
            "STORAGE_PRIV": str(self.pve / "priv" / "storage"),
            "PVE_DIR": str(self.pve),
            "RESTORE_ROOT": str(tmp_path / "tmp" / "pve-config-restore"),
            "RESTORE_OUTPUT": str(tmp_path / "var" / "pve-config-restore"),
        }.items():
            monkeypatch.setattr(self.m, name, value)
        monkeypatch.setattr(self.m, "_run", self)
        monkeypatch.setattr(self.m, "_which", lambda name: f"/usr/bin/{name}")
        monkeypatch.setattr(shutil, "chown", lambda *_args, **_kwargs: None)

        self.build = tmp_path / "build" / "osiris"
        self.build.mkdir(parents=True)
        self.storages: dict[str, dict] = {"backup-local": live_storage()}
        self.write_pw("backup-local", PASSWORD)
        (self.pve / "storage.cfg").write_text(
            "dir: local\n\tpath /var/lib/vz\n\npbs: backup-local\n\tdatastore backup\n"
            "\tserver xur.freender.internal\n\n",
            encoding="utf-8",
        )
        self.jobs: list[dict] = [live_job()]
        self.writes: list[list[str]] = []
        self.inactive: set[str] = set()
        self.add_error = ""
        self.running: set[str] = set()
        self.volumes = {"vm-flash:subvol-105-disk-0"}
        self.datastores: dict[str, list[dict]] = {}
        self.listing_error: dict[str, str] = {}
        self.envs: list[dict[str, str]] = []

    # --- fixtures ---

    def write_pw(self, name: str, password: str) -> None:
        (self.pve / "priv" / "storage" / f"{name}.pw").write_text(f"{password}\n")

    def stage(
        self,
        storage: str | None = STORAGE_PLAN,
        jobs: str | None = None,
        restore: str | None = None,
        tokens: str = TOKENS,
        key: bool = True,
    ) -> None:
        for name, text in (
            ("storage-plan.conf", storage),
            ("jobs-plan.conf", job_plan() if jobs is None else jobs),
            ("restore-plan.conf", restore),
        ):
            if text:
                (self.build / name).write_text(text, encoding="utf-8")
        (self.build / "pbs-tokens.env").write_text(tokens, encoding="utf-8")
        if key:
            (self.build / "pbs-encryption.key").write_bytes(b"KEY")

    def deploy(self, force: bool = False) -> None:
        ctx = InstallContext(
            host="osiris",
            script_dir=self.build.parent.parent,
            build_dir=self.build,
            env={},
            deploy_env={},
            file_map={},
            force_update=force,
        )
        self.m.install(ctx)

    # --- the fake commands ---

    def __call__(self, argv, **kwargs):
        handler = {
            "pvesh": self.pvesh,
            "pvesm": self.pvesm,
            "pct": self.pct,
            "proxmox-backup-client": self.client,
            "shred": self.shred,
        }[argv[0]]
        if argv[0] != "shred" and argv[1] not in ("get", "status", "path", "snapshots"):
            self.writes.append(list(argv))
        code, out, err = handler(argv, kwargs)
        return subprocess.CompletedProcess(argv, code, out, err)

    def shred(self, argv, _kwargs):
        Path(argv[-1]).unlink()
        return 0, "", ""

    def pvesh(self, argv, _kwargs):
        verb, path, *rest = argv[1:]
        if verb == "get" and path == "/storage":
            return 0, json.dumps(list(self.storages.values())), ""
        if verb == "get":
            return 0, json.dumps(self.jobs), ""
        values = options(rest)
        if verb == "create":
            self.jobs.append({"id": f"job{len(self.jobs)}", "type": "vzdump", **values})
            return 0, "", ""
        job = next(job for job in self.jobs if path.endswith(job["id"]))
        for key in str(values.pop("delete", "")).split(","):
            job.pop(key, None)
        job.update(values)
        return 0, "", ""

    def pvesm(self, argv, _kwargs):
        verb = argv[1]
        if verb == "status":
            return (1 if argv[-1] in self.inactive else 0), "", ""
        if verb == "path":
            return (0 if argv[-1] in self.volumes else 1), "", ""
        if verb == "remove":
            del self.storages[argv[2]]
            cfg = self.pve / "storage.cfg"
            cfg.write_text(cfg.read_text().split(f"pbs: {argv[2]}\n")[0])
            (self.pve / "priv" / "storage" / f"{argv[2]}.pw").unlink(missing_ok=True)
            return 0, "", ""
        name, rest = (argv[3], argv[4:]) if verb == "add" else (argv[2], argv[3:])
        if verb == "add" and self.add_error:
            return 255, "", self.add_error
        values = options(rest)
        if "password" in values:
            self.write_pw(name, str(values.pop("password")))
        if "encryption-key" in values:
            values["encryption-key"] = KEY_FP
        entry = self.storages.setdefault(name, {"storage": name, "type": "pbs"})
        for key in str(values.pop("delete", "")).split(","):
            entry.pop(key, None)
        entry.update(values)
        return 0, "", ""

    def pct(self, argv, _kwargs):
        if argv[1] == "status":
            state = "running" if argv[2] in self.running else "stopped"
            return 0, f"status: {state}\n", ""
        if argv[2] in self.running:
            return 255, "", "CT already running"
        self.running.add(argv[2])
        return 0, "", ""

    def client(self, argv, kwargs):
        repository = argv[argv.index("--repository") + 1]
        self.envs.append(kwargs["env"])
        if argv[1] == "snapshots":
            if repository in self.listing_error:
                return 1, "", self.listing_error[repository]
            return 0, json.dumps(self.datastores.get(repository, [])), ""
        target = Path(argv[4])
        lxc = target / "nodes" / "osiris" / "lxc"
        lxc.mkdir(parents=True)
        (lxc / "105.conf").write_text("onboot: 1\nrootfs: vm-flash:subvol-105-disk-0,size=8G\n")
        (target / "priv").mkdir()
        (target / "notifications.cfg").write_text("webhook: Alertmanager\n")
        (target / "priv" / "notifications.cfg").write_text("webhook: Alertmanager\n")
        return 0, "", ""


def snapshot(time: int, archive: str = "etc-pve") -> dict:
    return {
        "backup-type": "host",
        "backup-id": "pve-standalone",
        "backup-time": time,
        "files": [{"filename": f"{archive}.pxar.didx"}, {"filename": "index.json.blob"}],
    }


