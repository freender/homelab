def test_read_env_parses_plans_tokens_and_op_inject_output(node: Node, tmp_path: Path) -> None:
    path = tmp_path / "mixed.env"
    path.write_text(
        "# comment\n\nA='it'\"'\"'s'\nB=\"quoted value\"\nC=\nD='{{guestname}}'\n",
        encoding="utf-8",
    )

    assert node.m.read_env(path) == {
        "A": "it's",
        "B": "quoted value",
        "C": "",
        "D": "{{guestname}}",
    }


def test_read_env_never_echoes_a_malformed_line(node: Node, tmp_path: Path) -> None:
    path = tmp_path / "bad.env"
    path.write_text("PBS_PASSWORD='hunter2\n", encoding="utf-8")

    with pytest.raises(InstallError) as caught:
        node.m.read_env(path)

    assert "hunter2" not in str(caught.value)


