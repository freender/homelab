def test_a_drifted_username_is_set_without_resending_the_password(node: Node) -> None:
    node.storages["backup-local"]["username"] = "old@pbs"
    node.stage()

    node.deploy()

    assert node.storages["backup-local"]["username"] == "pve-backup@pbs"
