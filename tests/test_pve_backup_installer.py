def test_a_converged_node_writes_nothing(node: Node) -> None:
    node.stage()
    cfg = (node.pve / "storage.cfg").read_text()

    node.deploy()

    assert node.writes == []
    assert (node.pve / "storage.cfg").read_text() == cfg


def test_force_rewrites_storage_and_job_once_each_without_changing_them(node: Node) -> None:
    node.stage()

    node.deploy(force=True)

    assert [write[:2] for write in node.writes] == [["pvesm", "set"], ["pvesh", "set"]]
    assert "--password" in node.writes[0]
    assert node.storages["backup-local"] == live_storage()


