def test_a_rotated_password_is_sent(node: Node) -> None:
    node.write_pw("backup-local", "stale")
    node.stage()

    node.deploy()

    assert (node.pve / "priv" / "storage" / "backup-local.pw").read_text() == f"{PASSWORD}\n"
    assert len(node.writes) == 1


def test_an_emptied_namespace_is_deleted(node: Node) -> None:
    node.stage(storage=STORAGE_PLAN.replace("NAMESPACE='freender'", "NAMESPACE=''"))

    node.deploy()

