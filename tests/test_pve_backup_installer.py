"""pve-backup: remote installer (freender/homelab-ops#30).

`pvesh`/`pvesm`/`pct`/`proxmox-backup-client` are replaced by one in-memory PVE
node, and every absolute path is rebound under `tmp_path`, so each test asserts on
the resulting storages, jobs and files rather than on which commands ran.

What carries the risk, and what these pin:

* **A converged node writes nothing.** The live storages and jobs below are the
  JSON ace and osiris returned before the port; the bash rewrote all of them on
  every deploy, and an unchanged mtime is the canary's evidence.
* **A storage is never left undefined**: a failed recreate puts the old stanza and
  password back, and an existing encryption key is never replaced.
* **Every refusal comes before any write**, and **no staged credential survives
  any exit**.
* **Restore picks the newest snapshot that holds the archive** and never restarts
  a running container.
"""

