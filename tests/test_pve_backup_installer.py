def test_a_password_in_a_failed_set_is_not_reported(node: Node, monkeypatch) -> None:
    node.storages["backup-local"]["username"] = "old@pbs"
    node.stage()
    monkeypatch.setattr(
        node.m,
        "_run",
        lambda argv, **_kw: subprocess.CompletedProcess(
            argv,
            1 if argv[1] == "set" else 0,
            json.dumps(list(node.storages.values())) if argv[1] == "get" else "",
            f"bad value {PASSWORD}",
        ),
    )

    with pytest.raises(InstallError) as caught:
        node.deploy()

    assert PASSWORD not in str(caught.value)


def test_a_new_storage_is_added_with_its_prune_policy_then_encrypted(node: Node) -> None:
    node.storages.clear()
    node.stage()

    node.deploy()

    added = node.storages["backup-local"]
    assert added["prune-backups"] == "keep-all=1"
    assert added["encryption-key"] == KEY_FP
    assert [write[:2] for write in node.writes[:2]] == [["pvesm", "add"], ["pvesm", "set"]]


def test_an_existing_encryption_key_is_never_replaced(node: Node) -> None:
    node.storages["backup-local"]["encryption-key"] = "other"
