def restore_node(node: Node, enabled: bool = True, autostart: bool = False) -> None:
    node.datastores["xur-sync@pbs@cinci.internal:backup"] = [
        snapshot(1789273805),
        snapshot(1789360205),
        snapshot(1789400000, archive="other"),
    ]
    node.stage(restore=restore_plan(enabled, autostart, keyfile=node.m.PERSISTENT_KEYFILE))
    (node.build / "pbs-0.env").write_text('PBS_PASSWORD="pw0"\nPBS_FINGERPRINT="aa"\n')
    (node.build / "pbs-1.env").write_text('PBS_PASSWORD="pw1"\n')


def test_restore_is_skipped_when_every_listed_config_exists(node: Node) -> None:
    (node.pve / "nodes" / "osiris" / "lxc").mkdir(parents=True)
    (node.pve / "nodes" / "osiris" / "lxc" / "105.conf").write_text("x")
    restore_node(node)

    node.deploy()

    assert node.envs == []


def test_restore_is_skipped_without_force_when_lxc_restore_is_off(node: Node) -> None:
    restore_node(node, enabled=False)

    node.deploy()

    assert node.envs == []


def test_restore_fetches_the_newest_snapshot_that_holds_the_archive(node: Node) -> None:
    restore_node(node)

    node.deploy()

    restore_call = next(write for write in node.writes if write[1] == "restore")
    assert restore_call[2] == "host/pve-standalone/2026-09-14T04:30:05Z"
    assert restore_call[-2:] == ["--keyfile", node.m.PERSISTENT_KEYFILE]
    assert node.envs[-1]["PBS_PASSWORD"] == "pw0"
    live = (node.pve / "nodes" / "osiris" / "lxc" / "105.conf").read_text()
    assert "onboot: 0" in live
